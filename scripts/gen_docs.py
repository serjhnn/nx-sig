# gen_docs: writes COMMANDS.md from the help texts of
# the shell, so the docs and 'help' say the same
#
#   python scripts/gen_docs.py          write COMMANDS.md
#   python scripts/gen_docs.py --check  exit 1 if it is
#                                       out of date
#
# public functions:
#   commands_md()   the text of COMMANDS.md
#   up_to_date()    True if COMMANDS.md matches it

import os
import sys

# the help texts without color codes
os.environ["NO_COLOR"] = "1"

from commands import OWN_COMMANDS, NxSigShell, _doc
from storage import ROOT_DIR

PATH = os.path.join(ROOT_DIR, "COMMANDS.md")

INTRO = """\
# nX-sig commands

<!-- generated by scripts/gen_docs.py from the help
texts of the shell, don't edit it by hand: change the
docstring, then run python scripts/gen_docs.py -->

The commands of the shell (`./nxshell`), the same text
as `help <command>` shows.

Commands are `<action> <object> [arguments]`. The
actions are `ls` (list or show), `add` (save), `rm`
(delete, after confirmation), `run` and `stop`
(background tasks). The object is plural after `ls`
and singular everywhere else: `ls ladders`, but
`rm ladder 1`. An action alone lists its objects.
Keywords with a value, like `count 10 price 20.5`, may
come in either order.
"""


def _section(title, texts):
    return (
        f"## {title}\n\n```\n"
        + "\n\n".join(texts)
        + "\n```\n"
    )


def commands_md():
    shell = NxSigShell()
    sections = []
    titles = []
    for module in shell.objects.values():
        title = module.plural or module.name
        titles.append(title)
        sections.append(
            _section(
                title,
                [
                    _doc(getattr(module, action))
                    for action in module.actions()
                ],
            )
        )
    titles.append("other commands")
    sections.append(
        _section(
            "other commands",
            [
                _doc(getattr(shell, f"do_{name}"))
                for name in OWN_COMMANDS
            ],
        )
    )
    # GitHub's anchors: lowercase, spaces become '-'
    contents = "".join(
        f"- [{t}](#{t.replace(' ', '-')})\n" for t in titles
    )
    return "\n".join([INTRO, contents] + sections)


def up_to_date():
    try:
        with open(PATH, encoding="utf-8") as f:
            return f.read() == commands_md()
    except OSError:
        return False


if __name__ == "__main__":
    if sys.argv[1:] == ["--check"]:
        if up_to_date():
            print("ok: COMMANDS.md is up to date")
            sys.exit(0)
        print(
            "COMMANDS.md is out of date, run "
            "python scripts/gen_docs.py"
        )
        sys.exit(1)
    with open(PATH, "w", encoding="utf-8") as f:
        f.write(commands_md())
    print(f"wrote {os.path.relpath(PATH)}")
